-- sewing machines Pequeño Electrodoméstico, luggage Bolso, security cameras Camara. Mapped to 'Otros' on purpose (no canonical category): strollers,
-- cots, high chairs and baby gear, motorcycles. Left unmapped (the name decides): Aberturas (doors and windows), Accesorios (cameras, routers and
-- e-readers share one leaf) and the mixed parents. No node is a service, warranty or gift card.
-- Lookup CTEs instead of a literal per row: a string repeated three times is Sonar S1192.
