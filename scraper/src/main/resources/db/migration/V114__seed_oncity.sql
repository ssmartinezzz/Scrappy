-- (2,149 rows) is excluded in ServicioPorNombreDeCategoria: it waits for the supermercado rubro, so 47,705 products are kept.
-- Mixed: rubro_forzado stays NULL (RubroResolver decides by category) and rubro_por_defecto = 'hogar' for what no category decides (tyres,
-- stationery, baby gear, medical equipment); tecnologia is only ~8k of the 47.7k rows.
--
-- Leaf mapping: no new categories (V113 added the beauty ones this tree needs). The curated leaf outranks the name
-- (NormalizerService.SITIOS_DONDE_LA_HOJA_GANA). Each leaf takes the category that dominates it (>= 60% of its rows after the name classifier)
-- except where curated by hand: hair and shaving devices Pequeño Electrodoméstico, kitchenware Bazar, toys Juguete, paint and tool accessories,
-- TV supports and radios TV y Audio, suitcases Bolso. Strollers, cribs, pacifiers, dental, feminine hygiene, shaving foam and razor accessories map
-- to Otros on purpose: there is no category for them and the name would invent one. Left unmapped (the name decides): body-wash and "other
-- hygiene" (deodorants live there), supplements, chargers, gaming accessories, grinders and saws.
-- Lookup CTEs instead of a literal per row: a string repeated three times is Sonar S1192.
