#!/usr/bin/env node
// Downloads each store's own logo for every site in config.properties that has none, so adding a
// site never needs a hand-edited logo map. Only the stores' own homepages are contacted.
//
//   node scripts/fetch-site-logos.mjs            fetch the missing logos
//   node scripts/fetch-site-logos.mjs --check    list the missing ones, exit 1 if any (no network)
//   node scripts/fetch-site-logos.mjs --only a,b refetch those keys even if they have a logo
//
// Saves frontend/public/brand-logos/<key>.<ext>, adds a README row, and regenerates
// frontend/src/lib/brandLogos.generated.js (the file the frontend resolves `<key>` through).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const RAIZ = resolve(fileURLToPath(import.meta.url), '../..');
const CONFIG = resolve(RAIZ, 'scraper/src/main/resources/config.properties');
const LOGOS = resolve(RAIZ, 'frontend/public/brand-logos');
const README = resolve(LOGOS, 'README.md');
const MANIFIESTO = resolve(RAIZ, 'frontend/src/lib/brandLogos.generated.js');

const IMAGENES = new Set(['.png', '.jpg', '.jpeg', '.webp', '.svg', '.gif', '.ico', '.avif']);
const MAX_LADO_OK = 120;        // a wordmark 120+ wide is a real logo even when it is short
const MIN_LADO = 64;            // below this a favicon is a blur at chip size; take it only if nothing bigger exists
const MAX_BYTES = 3 * 1024 * 1024;
const NO_ES_LOGO = /whatsapp|facebook|instagram|twitter|tiktok|youtube|pinterest|pre-header|payment|medios|mercadopago|visa|mastercard/;
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

// ── manifest ────────────────────────────────────────────────────────────────

/** `under-armour.svg` is looked up as "under armour": same normalisation as brandLogos.js `clave`. */
function archivosDeLogos() {
  return readdirSync(LOGOS).filter(f => IMAGENES.has(extname(f).toLowerCase())).sort((a, b) => a.localeCompare(b));
}

function regenerarManifiesto() {
  const entradas = {};
  for (const f of archivosDeLogos()) {
    entradas[basename(f, extname(f)).toLowerCase().replaceAll('-', ' ')] = f;
  }
  const cuerpo = Object.entries(entradas).map(([k, f]) => `  ${JSON.stringify(k)}: ${JSON.stringify(f)},`).join('\n');
  const texto = `// Generated by scripts/fetch-site-logos.mjs from public/brand-logos/. Do not edit by hand.\n`
    + `export const LOGO_FILES_BY_NAME = {\n${cuerpo}\n};\n`;
  writeFileSync(MANIFIESTO, texto);
}

// ── sites ───────────────────────────────────────────────────────────────────

function sitiosDeConfig() {
  const sitios = {};
  for (const linea of readFileSync(CONFIG, 'utf8').split('\n')) {
    const m = /^sitio\.([a-z0-9_]+)\.url=(\S+)/.exec(linea);
    if (m) sitios[m[1]] = m[2];
  }
  return sitios;
}

async function cargarLado() {
  // Imported after the manifest is regenerated, so a logo dropped in by hand counts as present.
  const url = `${new URL('../frontend/src/lib/', import.meta.url)}`;
  const { brandLogoFile, SITIO_LOGO_MARCA } = await import(`${url}brandLogos.js?${Date.now()}`);
  const { LABELS } = await import(`${url}sitios.js?${Date.now()}`);
  return { brandLogoFile, SITIO_LOGO_MARCA, LABELS };
}

// ── HTML ────────────────────────────────────────────────────────────────────

function atributos(etiqueta) {
  const attrs = {};
  // Attributes are written `name=value` with no spaces around `=` in every homepage this reads.
  for (const [, nombre, crudo] of etiqueta.matchAll(/([\w:-]+)=("[^"]*"|'[^']*'|[^\s>]+)/g)) {
    const valor = /^["']/.test(crudo) ? crudo.slice(1, -1) : crudo;
    attrs[nombre.toLowerCase()] = valor.replaceAll('&amp;', '&');
  }
  return attrs;
}

const ladoDeclarado = sizes => Math.max(0, ...(sizes || '').split(/\s+/).map(s => Number.parseInt(s, 10) || 0));

function deLinks(html, agregar) {
  for (const [etiqueta] of html.matchAll(/<link\b[^>]*>/gi)) {
    const a = atributos(etiqueta);
    const rel = (a.rel || '').toLowerCase();
    if (rel.includes('apple-touch-icon')) agregar(a.href, 0, ladoDeclarado(a.sizes) || 180);
    else if (/\bicon\b/.test(rel)) agregar(a.href, 3, ladoDeclarado(a.sizes));
  }
}

function prioridadDeImg(pistas, clave) {
  if (pistas.includes('header-logo')) return 0.5;
  if (pistas.includes(clave)) return 1;
  return 1.5;
}

// The store's own header logo: an <img> that calls itself a logo, outside the footer. One that
// names the store beats a generic one (a marketplace page also carries its sub-brands' logos).
function deImgs(html, clave, agregar) {
  const cabecera = html.split(/<footer\b/i)[0];
  for (const [etiqueta] of cabecera.matchAll(/<img\b[^>]*>/gi)) {
    const a = atributos(etiqueta);
    const pistas = `${a.src} ${a['data-src']} ${a.alt} ${a.class} ${a.id}`.toLowerCase();
    if (!pistas.includes('logo') || NO_ES_LOGO.test(pistas)) continue;
    const src = a.src && !a.src.startsWith('data:') ? a.src : a['data-src'];
    agregar(src, prioridadDeImg(pistas, clave));
  }
}

function deMetas(html, agregar) {
  for (const [etiqueta] of html.matchAll(/<meta\b[^>]*>/gi)) {
    const a = atributos(etiqueta);
    const esImagen = a.property === 'og:image' || a.name === 'twitter:image';
    if (esImagen && /logo/i.test(a.content || '')) agregar(a.content, 2);
  }
}

/** Candidate URLs in the order worth trying: [prioridad, lado declarado] ascending / descending. */
function candidatos(html, base, clave) {
  const lista = [];
  const agregar = (href, prioridad, lado = 0) => {
    if (!href || href.startsWith('data:')) return;
    try { lista.push({ url: new URL(href.trim(), base).href, prioridad, lado }); } catch { /* bad href */ }
  };
  deLinks(html, agregar);
  deImgs(html, clave, agregar);
  deMetas(html, agregar);
  agregar('/favicon.ico', 4);
  agregar('/apple-touch-icon.png', 5, 180);
  const vistos = new Set();
  return lista
    .filter(c => !vistos.has(c.url) && vistos.add(c.url))
    .sort((a, b) => a.prioridad - b.prioridad || b.lado - a.lado);
}

// ── image bytes ─────────────────────────────────────────────────────────────

function leerJpeg(buf) {
  for (let i = 2; i + 9 < buf.length;) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marcador = buf[i + 1];
    if (marcador >= 0xc0 && marcador <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marcador)) {
      return { ext: '.jpg', h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
    }
    i += 2 + buf.readUInt16BE(i + 2);
  }
  return { ext: '.jpg', w: 0, h: 0 };
}

function leerWebp(buf) {
  const tipo = buf.subarray(12, 16).toString('latin1');
  if (tipo === 'VP8X') return { ext: '.webp', w: 1 + buf.readUIntLE(24, 3), h: 1 + buf.readUIntLE(27, 3) };
  if (tipo === 'VP8 ') return { ext: '.webp', w: buf.readUInt16LE(26) & 0x3fff, h: buf.readUInt16LE(28) & 0x3fff };
  return { ext: '.webp', w: 0, h: 0 };
}

function leerIco(buf) {
  let lado = 0;
  for (let i = 0; i < buf.readUInt16LE(4); i++) lado = Math.max(lado, buf[6 + i * 16] || 256, buf[7 + i * 16] || 256);
  return { ext: '.ico', w: lado, h: lado };
}

/** `{ ext, w, h }` from the magic bytes, or null when it is not an image we keep. w/h 0 = vector/unknown. */
function leerImagen(buf) {
  const ascii = (a, b) => buf.subarray(a, b).toString('latin1');
  if (ascii(1, 4) === 'PNG') return { ext: '.png', w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
  if (ascii(0, 3) === 'GIF') return { ext: '.gif', w: buf.readUInt16LE(6), h: buf.readUInt16LE(8) };
  if (buf[0] === 0xff && buf[1] === 0xd8) return leerJpeg(buf);
  if (ascii(0, 4) === 'RIFF' && ascii(8, 12) === 'WEBP') return leerWebp(buf);
  if (buf[0] === 0 && buf[1] === 0 && buf[2] === 1 && buf[3] === 0) return leerIco(buf);
  if (/<svg[\s>]/i.test(ascii(0, Math.min(buf.length, 2048)))) return { ext: '.svg', w: 0, h: 0 };
  return null;
}

async function descargar(url, accept, limite = MAX_BYTES) {
  const r = await fetch(url, { headers: { 'user-agent': UA, accept }, redirect: 'follow', signal: AbortSignal.timeout(20000) });
  if (!r.ok) throw new Error(`HTTP ${r.status}`);
  const buf = Buffer.from(await r.arrayBuffer());
  if (buf.length > limite) throw new Error('too big');
  return { buf, url: r.url };
}

// ── one site ────────────────────────────────────────────────────────────────

async function logoDe(clave, urlConfig) {
  const inicio = new URL('/', urlConfig).href;
  let lista;
  try {
    const { buf, url: final } = await descargar(inicio, 'text/html,*/*', 12 * MAX_BYTES);
    lista = candidatos(buf.toString('utf8'), final, clave);
  } catch (e) {
    // A WAF in front of the page often leaves the static icon paths open.
    lista = ['/apple-touch-icon.png', '/favicon.ico'].map(p => ({ url: new URL(p, inicio).href }));
    console.log(`  (${clave}: homepage ${e.message}, trying the standard icon paths)`);
  }
  let mejor = null;
  const motivos = [];
  for (const c of lista) {
    let imagen;
    try {
      const d = await descargar(c.url, 'image/*,*/*;q=0.5');
      const info = leerImagen(d.buf);
      if (!info) { motivos.push(`${c.url}: not an image`); continue; }
      imagen = { ...info, buf: d.buf, origen: d.url };
    } catch (e) {
      motivos.push(`${c.url}: ${e.message}`);
      continue;
    }
    const lado = Math.min(imagen.w, imagen.h);
    if (imagen.ext === '.svg' || Math.max(imagen.w, imagen.h) >= MAX_LADO_OK || lado >= MIN_LADO) return { ...imagen, chico: false };
    if (!mejor || lado > Math.min(mejor.w, mejor.h)) mejor = imagen;
  }
  if (mejor) return { ...mejor, chico: true };
  throw new Error(motivos.length ? motivos.slice(0, 3).join(' | ') : 'no logo candidates in the homepage');
}

function anotarReadme(etiqueta, archivo, origen) {
  const fila = `| ${etiqueta} | \`${archivo}\` | ${origen} | store site |`;
  const lineas = readFileSync(README, 'utf8').split('\n');
  const i = lineas.findIndex(l => l.includes(`\`${archivo}\``));
  if (i >= 0) lineas[i] = fila;
  else {
    let fin = lineas.length - 1;
    while (fin > 0 && lineas[fin].trim() === '') fin--;
    lineas.splice(fin + 1, 0, fila);
  }
  writeFileSync(README, lineas.join('\n'));
}

// ── main ────────────────────────────────────────────────────────────────────

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const only = args.includes('--only') ? new Set(args[args.indexOf('--only') + 1].split(',')) : null;

  regenerarManifiesto();
  const { brandLogoFile, SITIO_LOGO_MARCA, LABELS } = await cargarLado();
  const sitios = sitiosDeConfig();
  const faltan = Object.keys(sitios)
    .filter(k => (only ? only.has(k) : !brandLogoFile(SITIO_LOGO_MARCA[k] ?? k)))
    .sort((a, b) => a.localeCompare(b));

  const sinEtiqueta = Object.keys(sitios).filter(k => !LABELS[k]);
  if (sinEtiqueta.length) console.log(`No LABELS entry in src/lib/sitios.js for: ${sinEtiqueta.join(', ')}`);
  if (check || faltan.length === 0) {
    console.log(faltan.length ? `Missing logo: ${faltan.join(' ')}` : 'Every site has a logo.');
    process.exit(check && faltan.length ? 1 : 0);
  }

  console.log(`Fetching ${faltan.length} logos from the stores' own homepages…`);
  const fallos = [];
  const cola = [...faltan];
  const procesar = async (k) => {
    try {
      const r = await logoDe(k, sitios[k]);
      const archivo = `${k}${r.ext}`;
      writeFileSync(resolve(LOGOS, archivo), r.buf);
      anotarReadme(LABELS[k] ?? k, archivo, r.origen);
      const dim = r.w ? `${r.w}x${r.h}` : 'vector';
      console.log(`  ok    ${k.padEnd(18)} ${archivo.padEnd(24)} ${dim}${r.chico ? '  (small: only a favicon was available)' : ''}  <- ${r.origen}`);
    } catch (e) {
      fallos.push(k);
      console.log(`  FAIL  ${k.padEnd(18)} ${e.message}`);
    }
  };
  // Four workers drain one queue: a site at a time each, so no store sees more than one request at once.
  const trabajador = async () => {
    const k = cola.shift();
    if (!k) return;
    await procesar(k);
    await trabajador();
  };
  await Promise.all(Array.from({ length: 4 }, trabajador));

  regenerarManifiesto();
  if (fallos.length) console.log(`\nNo logo for: ${fallos.toSorted((a, b) => a.localeCompare(b)).join(' ')}. Drop the file in by hand as <key>.<ext> and rerun.`);
}

await main();
